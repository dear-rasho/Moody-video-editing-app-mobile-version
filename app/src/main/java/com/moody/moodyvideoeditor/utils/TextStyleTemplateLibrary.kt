        private fun metallic(
            id: String,
            name: String,
            description: String,
            icon: String,
            font: String,
            animation: String,
            color: Long,
            highlight: Long,
            shade: Long,
            edge: Long,
            glow: Long,
            shadow: Long
        ) = TextStyleTemplate(
            id = id,
            name = name,
            description = description,
            icon = icon,
            style = TextState(
                fontFamily = font,
                fontSize = 48,
                fontWeight = "bold",
                color = color,
                strokeEnabled = true,
                strokeWidth = 2f,
                strokeColor = edge,
                glowEnabled = true,
                glowColor = glow,
                glowRadius = 13f,
                gradientEnabled = true,
                gradientColor1 = highlight,
                gradientColor2 = shade,
                shadowEnabled = true,
                shadowColor = shadow,
                shadowBlur = 2f,
                shadowOffsetX = 3f,
                shadowOffsetY = 5f,
                animation = animation,
                animationDuration = 0.7f
            )
        )
    fun applyTo(current: TextState, templateId: String): TextState {
        val style = templates.firstOrNull { it.id == templateId }?.style
            ?: return current
        return current.copy(
            fontFamily = style.fontFamily,
            fontSize = style.fontSize,
            fontWeight = style.fontWeight,
            fontStyle = style.fontStyle,
            color = style.color,
            strokeEnabled = style.strokeEnabled,
            strokeWidth = style.strokeWidth,
            strokeColor = style.strokeColor,
            glowEnabled = style.glowEnabled,
            glowColor = style.glowColor,
            glowRadius = style.glowRadius,
            gradientEnabled = style.gradientEnabled,
            gradientColor1 = style.gradientColor1,
            gradientColor2 = style.gradientColor2,
            gradientAngle = style.gradientAngle,
            gradientStartX = style.gradientStartX,
            gradientStartY = style.gradientStartY,
            gradientEndX = style.gradientEndX,
            gradientEndY = style.gradientEndY,
            shadowEnabled = style.shadowEnabled,
            shadowColor = style.shadowColor,
            shadowBlur = style.shadowBlur,
            shadowOffsetX = style.shadowOffsetX,
            shadowOffsetY = style.shadowOffsetY,
            letterSpacing = style.letterSpacing,
            lineHeight = style.lineHeight,
            alignment = style.alignment,
            maxWidth = style.maxWidth,
            animation = style.animation,
            animationDuration = style.animationDuration,
            captionPresetId = null,
            captionPresetAnimation = "none",
            templateId = templateId,
            textureUri = null,
            textureMimeType = null,
            segments = emptyList()
        )
    }
